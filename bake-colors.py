#!/usr/bin/env python3
"""Compute each icon's tile and glow colour on the Mac and bake them into apps.js.

The launcher normally samples icon pixels with a canvas at runtime, but webOS serves the app
from file:// so the canvas is tainted and getImageData() throws. Doing it here instead gives
every tile its real colour.

    python3 bake-colors.py /path/to/app
"""
import json
import os
import sys

from PIL import Image


def rgb_to_hsv(c):
    r, g, b = c[0] / 255.0, c[1] / 255.0, c[2] / 255.0
    mx, mn = max(r, g, b), min(r, g, b)
    d = mx - mn
    h = 0.0
    if d:
        if mx == r:
            h = ((g - b) / d) % 6
        elif mx == g:
            h = (b - r) / d + 2
        else:
            h = (r - g) / d + 4
        h *= 60
        if h < 0:
            h += 360
    return [h, (d / mx) if mx else 0.0, mx]


def hsv_to_rgb(hsv):
    h, s, v = hsv
    c = v * s
    x = c * (1 - abs((h / 60) % 2 - 1))
    m = v - c
    if h < 60:
        rgb = (c, x, 0)
    elif h < 120:
        rgb = (x, c, 0)
    elif h < 180:
        rgb = (0, c, x)
    elif h < 240:
        rgb = (0, x, c)
    elif h < 300:
        rgb = (x, 0, c)
    else:
        rgb = (c, 0, x)
    return [int(round((k + m) * 255)) for k in rgb]


def vivid_color(px):
    """The most saturated, not-too-dark pixel, or the lifted average."""
    best, best_score = None, -1.0
    total, n = [0, 0, 0], 0
    for r, g, b, a in px:
        if a < 128:
            continue
        total[0] += r
        total[1] += g
        total[2] += b
        n += 1
        hsv = rgb_to_hsv((r, g, b))
        score = hsv[1] * min(1.0, hsv[2] * 1.4)
        if score > best_score:
            best_score, best = score, (r, g, b)
    if not n:
        return [68, 68, 68]
    if best_score < 0.25:
        avg = rgb_to_hsv((total[0] / n, total[1] / n, total[2] / n))
        avg[2] = max(avg[2], 0.55)
        return hsv_to_rgb(avg)
    h = rgb_to_hsv(best)
    h[1] = min(1.0, h[1] * 1.1)
    h[2] = max(0.5, h[2])
    return hsv_to_rgb(h)


def parse_hex(s):
    s = (s or "").lstrip("#")
    if len(s) != 6:
        return None
    try:
        return [int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16)]
    except ValueError:
        return None


def is_dull(c):
    """White, black or near-grey: says nothing about the app."""
    hsv = rgb_to_hsv(c)
    return hsv[1] < 0.15 and (hsv[2] > 0.85 or hsv[2] < 0.1)


def to_hex(c):
    return "#%02x%02x%02x" % (c[0], c[1], c[2])


def analyse(path, icon_color):
    im = Image.open(path).convert("RGBA")
    w, h = im.size

    # The icon's own background: a corner pixel, or the middle of the left edge for rounded
    # icons whose corners are transparent. Transparent on both means a glyph on no background.
    corner = im.getpixel((min(2, w - 1), min(2, h - 1)))
    edge = corner if corner[3] > 200 else im.getpixel((min(2, w - 1), h // 2))

    small = im.resize((12, 12), Image.BILINEAR)
    vivid = vivid_color(list(small.getdata()))

    if edge[3] > 200:
        return to_hex(edge[:3]), False, to_hex(vivid)

    # Glyph on transparency: tint it with the app's declared colour when that colour means
    # something, otherwise sit it on neutral grey and glow in the icon's own vivid colour.
    declared = parse_hex(icon_color)
    if declared and not is_dull(declared):
        return to_hex(declared), True, to_hex(declared)
    return "#2c2c2e", True, to_hex(vivid)


def main(app_dir):
    apps_js = os.path.join(app_dir, "apps.js")
    with open(apps_js, encoding="utf-8") as f:
        src = f.read()
    data = json.loads(src[src.index("{"): src.rindex("}") + 1])

    for app in data["apps"]:
        icon = os.path.join(app_dir, app["icon"])
        if not os.path.exists(icon):
            print("  no icon file for %s" % app["id"])
            continue
        tile, glyph, glow = analyse(icon, app.get("iconColor"))
        app["tileColor"], app["glyph"], app["glowColor"] = tile, glyph, glow
        print("  %-32s tile %s  glow %s%s" % (app["id"], tile, glow, "  (glyph)" if glyph else ""))

    with open(apps_js, "w", encoding="utf-8") as f:
        f.write("// Generated by sync-apps.py, colours by bake-colors.py.\n")
        f.write("window.TV_APPS = " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n")
    print("Baked colours for %d apps." % len(data["apps"]))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else sys.exit("usage: bake-colors.py <app dir>"))
